# "75 วันของพ่อ": lay the Charon phrases on a fresh timeline with chosen pauses, write story2/vo.js + segments.
import json, subprocess
def split(f, n):
    return json.loads(subprocess.run(['venv/bin/python', '-I', 'scripts/split_phrases.py', f, str(n)], capture_output=True, text=True, check=True).stdout)['phrases']
src = {'A': split('story2/vo/A44.wav', 8), 'B': split('story2/vo/B44.wav', 8), 'C': split('story2/vo/C44.wav', 5), 'D': split('story2/vo/D44.wav', 8)}
names = {'A': ['มือถือเครื่องใหม่', 'ราคาสามหมื่น', 'กดสั่งซื้อตอนเที่ยงคืน', 'ใช้เวลาแค่ห้านาที', 'แต่สำหรับพ่อ', 'เงินก้อนนี้', 'คือเหงื่อ', 'เจ็ดสิบห้าวัน'],
         'B': ['พ่อเป็นช่างปูน', 'ค่าแรงวันละสี่ร้อยบาท', 'แบกปูนกลางแดด', 'จนหลังแทบขาด', 'ส่วนมือถือของพ่อ', 'ยังเป็นปุ่มกด', 'เครื่องเก่า', 'ที่จอแตกเกือบหมด'],
         'C': ['[sigh]', 'แต่มือถือสามหมื่น', 'ที่ลูกถือทุกวัน', 'กลับไม่เคยโทรหาพ่อ', 'สักวัน'],
         'D': ['วันนี้', 'ลองโทรหาพ่อสักครั้ง', 'ให้พ่อได้ยินเสียง', 'ที่เฝ้ารอฟัง', 'เพราะของขวัญที่พ่ออยากได้', 'ไม่ใช่เงินทอง', 'แต่คือคำถามง่ายๆ ว่า', 'พ่อเหนื่อยไหม']}
# pause AFTER each phrase (s); None at part ends handled by the part gaps below
gaps = {'A': [0.35, 0.4, 0.35, 0.55, 0.5, 0.45, 0.45, 0.7], 'B': [0.35, 0.5, 0.4, 0.55, 0.4, 0.4, 0.35, 0.7],
        'C': [0.3, 0.45, 0.45, 0.75, 0.0], 'D': [0.5, 0.4, 0.35, 0.6, 0.45, 0.6, 0.8, 0.0]}
TITLE = 2.3; END = 3.2
t = 0.4
ph = []
for k in 'ABCD':
    if k == 'D': t += TITLE + 0.2
    for i, (a, b) in enumerate(src[k]):
        ph.append({'id': f'{k}{i}', 'take': k, 'name': names[k][i], 'src': [a, b], 'on': round(t, 3), 'off': round(t + b - a, 3)})
        t += (b - a) + gaps[k][i]
title_at = [p for p in ph if p['id'] == 'C4'][0]['off'] + 0.2
end_at = ph[-1]['off'] + 0.45
DUR = round(end_at + END, 2)
g = {p['id']: p for p in ph}
for p in ph: print(f"{p['id']:3s} {p['name']:24s} {p['on']:6.2f}-{p['off']:6.2f}")
print('title', round(title_at, 2), 'end card', round(end_at, 2), 'DUR', DUR)
on = lambda k: g[k]['on']; off = lambda k: g[k]['off']; d = lambda k: g[k]['off'] - g[k]['on']
P = {p['id']: p['on'] for p in ph}
P.update({'title': round(title_at, 3), 'end': round(end_at, 3), 'DUR': DUR})
def part(t_, s, k, at=None, dd=None): return {'t': t_, 's': s, 'at': round(at if at is not None else on(k), 3), 'd': round(dd if dd is not None else d(k), 3)}
cues = [
 [part('มือถือเครื่องใหม่', 'w', 'A0')],
 [part('ราคา', 'w', 'A1', dd=0.35), part('30,000 บาท', 'r', 'A1', at=on('A1') + 0.3, dd=0.8)],
 [part('กดสั่งซื้อตอนเที่ยงคืน', 'w', 'A2')],
 [part('ใช้เวลาแค่', 'w', 'A3', dd=0.8), part('5 นาที', 'r', 'A3', at=on('A3') + 0.85, dd=0.6)],
 [part('แต่สำหรับพ่อ', 'y', 'A4')],
 [part('เงินก้อนนี้', 'w', 'A5'), part(' คือเหงื่อ', 'w', 'A6')],
 [part('75 วัน', 'r', 'A7')],
 [part('พ่อเป็นช่างปูน', 'w', 'B0')],
 [part('ค่าแรงวันละ', 'w', 'B1', dd=1.2), part('400 บาท', 'r', 'B1', at=on('B1') + 1.2, dd=0.9)],
 [part('แบกปูนกลางแดด', 'w', 'B2')],
 [part('จนหลังแทบขาด', 'y', 'B3')],
 [part('ส่วนมือถือของพ่อ', 'w', 'B4')],
 [part('ยังเป็นปุ่มกด', 'w', 'B5')],
 [part('เครื่องเก่า', 'w', 'B6'), part(' ที่จอแตกเกือบหมด', 'w', 'B7')],
 [part('แต่มือถือ', 'w', 'C1', dd=0.7), part('30,000', 'r', 'C1', at=on('C1') + 0.65, dd=0.8)],
 [part('ที่ลูกถือทุกวัน', 'w', 'C2')],
 [part('กลับไม่เคยโทรหาพ่อ', 'w', 'C3'), part('สักวัน', 'r', 'C4')],
 [part('วันนี้', 'y', 'D0'), part(' ลองโทรหาพ่อสักครั้ง', 'y', 'D1')],
 [part('ให้พ่อได้ยินเสียง', 'w', 'D2'), part(' ที่เฝ้ารอฟัง', 'w', 'D3')],
 [part('เพราะของขวัญที่พ่ออยากได้', 'w', 'D4')],
 [part('ไม่ใช่เงินทอง', 'w', 'D5')],
 [part('แต่คือคำถามง่ายๆ ว่า', 'w', 'D6')],
 [part('พ่อเหนื่อยไหม', 'r', 'D7')],
]
CUES = []
for j, parts in enumerate(cues):
    a = parts[0]['at']
    last_end = max(p['at'] + p['d'] for p in parts)
    nxt = cues[j + 1][0]['at'] if j + 1 < len(cues) else 99
    b = min(nxt - 0.04, last_end + 0.6)
    CUES.append({'a': round(a, 3), 'b': round(b, 3), 'parts': parts})
CUES[-1]['b'] = round(end_at - 0.05, 3)
open('story2/vo.js', 'w').write('// generated by story2/place.py\nconst VO = ' + json.dumps({'P': P, 'CUES': CUES}, ensure_ascii=False) + ';\n')
json.dump([{'file': f'story2/vo/{p["take"]}44.wav', 'src': p['src'], 'on': p['on'], 'name': p['name']} for p in ph], open('story2/segments.json', 'w'), ensure_ascii=False, indent=1)
