# "52 ปีกับกระทงสองใบ": "ถ้า..." hook (take H), then Puck narration at 1.2x. Each take is kept whole; scene keys are anchored to
# Whisper word timestamps (first word clamped to the measured speech onset). Writes story10/vo.js + segments.json.
import json
W = json.load(open('story10/vo/words.json'))
BND = json.load(open('story10/vo/bounds.json'))

def anchors(k, specs):
    toks = W[k]; txt = ''; idx = []
    for i, (w, a, b) in enumerate(toks):
        for _ in w: idx.append(i)
        txt += w
    out = {}
    for name, sub, after in specs:
        start = txt.find(sub, out[after][1] + 1 if after else 0)
        assert start >= 0, (k, name, sub, txt)
        while txt[start] == ' ': start += 1
        out[name] = (toks[idx[start]][1], start)
    return {n: v[0] for n, v in out.items()}, toks[0][1], toks[-1][2]

