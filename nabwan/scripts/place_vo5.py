# Place Gemini Charon phrases on the v4 timeline: each phrase goes to the old phrase onset (shifted only as much
# as needed to avoid overlap), then write demo/vo5.js (P landmarks + CUES) and demo/vo5_segments.json for the mix.
import json, subprocess
SPL = 'scripts/split_phrases.py'
takes = {'A': ('gemini/v_A144.wav', 9), 'B': ('gemini/v_B44.wav', 8), 'C': ('gemini/v_C144.wav', 8)}
seg = {}
for k, (f, n) in takes.items():
    out = subprocess.run(['venv/bin/python', '-I', SPL, f, str(n)], capture_output=True, text=True, check=True).stdout
    seg[k] = json.loads(out)['phrases']
names = {'A': ['ถ้าคุณ', 'ทำงานไกลบ้าน', 'ห่างกันนาน', 'กว่าจะได้กลับ', 'ก็แค่ปีละสองครั้ง', 'เคยนับบ้างไหม', 'ว่าเวลาที่ยังเหลือ', 'จะได้เจอพ่อแม่', 'อีกกี่วัน'],
         'B': ['[sigh]', 'ปีหนึ่ง', 'ได้อยู่บ้านพร้อมหน้ากัน', 'แค่สิบวัน', 'แต่แม่', 'นับวันรอ', 'สามร้อยห้าสิบห้าวัน', 'โดยไม่เคยท้อ'],
         'C': ['ไม่ต้องรอสงกรานต์', 'ไม่ต้องรอปีใหม่', 'ว่างเมื่อไหร่', 'กลับไปหาแม่เถอะนะ', 'เพราะแม่', 'ไม่ได้รอแค่วันหยุด', 'แต่รอลูก', 'ทุกวัน']}
target = {'A': [0.57, 1.86, 3.74, 5.42, 6.46, 9.11, 10.46, 11.97, 13.42],
          'B': [14.79, 15.75, 17.12, 19.43, 21.83, 22.95, 24.07, 26.72],
          'C': [30.42, 31.90, 33.91, 34.86, 37.54, 38.38, 40.14, 41.51]}
ph = []
for k in 'ABC':
    for i, (a, b) in enumerate(seg[k]):
        ph.append({'take': k, 'i': i, 'name': names[k][i], 'src': (a, b), 'd': round(b - a, 3), 't': target[k][i]})
end = -1
for j, p in enumerate(ph):
    nxt = ph[j + 1]['t'] if j + 1 < len(ph) else 99
    lo = end + 0.22
    pref = min(p['t'], nxt - 0.2 - p['d'])
    s = max(lo, max(p['t'] - 0.25, pref))
    p['on'] = round(s, 3); p['off'] = round(s + p['d'], 3); end = p['off']
for p in ph:
    print(f"{p['take']}{p['i']} {p['name']:24s} old {p['t']:6.2f}  new {p['on']:6.2f}-{p['off']:6.2f}  shift {p['on'] - p['t']:+.2f}")
g = {f"{p['take']}{p['i']}": p for p in ph}
on = lambda k: g[k]['on']; d = lambda k: g[k]['d']
P = {'thakhun': on('A0'), 'tamngan': on('A1'), 'hang': on('A2'), 'kwa': on('A3'), 'kor': on('A4'), 'song': on('A4') + 0.49 * d('A4'),
     'khoei': on('A5'), 'wa': on('A6'), 'ja': on('A7'), 'eek': on('A8'),
     'sigh': on('B0'), 'pi': on('B1'), 'dai': on('B2'), 'kae': on('B3'), 'sip': on('B3') + 0.28 * d('B3'), 'tae': on('B4'), 'nap': on('B5'),
     'sam': on('B6'), 'hawan': on('B6') + 0.72 * d('B6'), 'doi': on('B7'),
     'mai1': on('C0'), 'mai2': on('C1'), 'pimai': on('C1') + 0.40 * d('C1'), 'wang': on('C2'), 'klap': on('C3'), 'pro': on('C4'),
     'maidai': on('C5'), 'taerao': on('C6'), 'luk': on('C6') + 0.63 * d('C6'), 'tuk': on('C7')}
P = {k: round(v, 3) for k, v in P.items()}
def part(t, s, k, at=None, dd=None): return {'t': t, 's': s, 'at': round(at if at is not None else on(k), 3), 'd': round(dd if dd is not None else d(k), 3)}
cues = [
  ([part('ถ้าคุณทำงานไกลบ้าน', 'w', 'A0', dd=g['A1']['off'] - on('A0'))], 'A1', None, None),
  ([part('ห่างกันนาน', 'w', 'A2')], 'A2', 5.28, None),
  ([part('กว่าจะได้กลับ ก็แค่ปีละ', 'w', 'A3', dd=P['song'] - on('A3')), part('2 ครั้ง', 'r', 'A4', at=P['song'] - 0.02, dd=0.6)], 'A4', 8.94, None),
  ([part('เคยนับบ้างไหม', 'w', 'A5')], 'A5', None, None),
  ([part('ว่าเวลาที่ยังเหลือ', 'w', 'A6'), part(' จะได้เจอพ่อแม่', 'w', 'A7')], 'A7', None, None),
  ([part('อีกกี่วัน', 'r', 'A8')], 'A8', 14.55, None),
  ([part('ปีหนึ่ง', 'y', 'B1'), part(' ได้อยู่บ้านพร้อมหน้ากัน', 'y', 'B2')], 'B2', None, None),
  ([part('แค่', 'w', 'B3', dd=0.3), part('10 วัน', 'r', 'B3', at=P['sip'] - 0.02, dd=0.7)], 'B3', 21.65, None),
  ([part('แต่แม่', 'w', 'B4'), part('นับวันรอ', 'w', 'B5')], 'B5', None, None),
  ([part('355 วัน', 'r', 'B6')], 'B6', None, None),
  ([part('โดยไม่เคยท้อ', 'y', 'B7')], 'B7', 28.0, None),
  ([part('ไม่ต้องรอสงกรานต์', 'w', 'C0')], 'C0', None, None),
  ([part('ไม่ต้องรอปีใหม่', 'w', 'C1')], 'C1', None, None),
  ([part('ว่างเมื่อไหร่', 'y', 'C2')], 'C2', 34.72, None),
  ([part('กลับไปหาแม่เถอะนะ', 'y', 'C3')], 'C3', None, 1650),
  ([part('เพราะแม่', 'w', 'C4'), part('ไม่ได้รอแค่วันหยุด', 'w', 'C5')], 'C5', None, 1650),
  ([part('แต่รอลูก', 'w', 'C6'), part('ทุกวัน', 'r', 'C7')], 'C7', 42.6, 1650),
]
CUES = []
for j, (parts, last, cap, top) in enumerate(cues):
    a = parts[0]['at']
    nxt = cues[j + 1][0][0]['at'] if j + 1 < len(cues) else 99
    b = min(nxt - 0.04, g[last]['off'] + 0.75)
    if cap: b = min(b, cap)
    c = {'a': round(a, 3), 'b': round(b, 3), 'parts': parts}
    if top: c['top'] = top
    CUES.append(c)
open('demo/vo5.js', 'w').write('// generated by scripts/place_vo5.py — Gemini Charon narration timeline\nconst VO5 = ' +
                                json.dumps({'P': P, 'CUES': CUES}, ensure_ascii=False) + ';\n')
json.dump([{'file': takes[p['take']][0], 'src': p['src'], 'on': p['on'], 'name': p['name']} for p in ph], open('demo/vo5_segments.json', 'w'), ensure_ascii=False, indent=1)
print('P', P)
