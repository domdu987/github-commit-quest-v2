# "47 ครั้งที่ลบข้อความ" v3: Puck voice at 1.2x, plain brisk narration. Each take is kept whole (natural flow); scene keys (A0..D6)
# are anchored to Whisper word timestamps so the existing scenes retime themselves. Writes story4/vo.js + segments.json.
import json
W = json.load(open('story4/vo3/words.json'))
BND = json.load(open('story4/vo3/bounds.json'))  # measured speech onset/tail; Whisper puts some first words at 0.0

def anchors(k, specs):
    toks = W[k]; txt = ''; idx = []
    for i, (w, a, b) in enumerate(toks):
        for _ in w: idx.append(i)
        txt += w
    out, pos = {}, 0
    for name, sub, after in specs:
        start = txt.find(sub, out.get(after, (0, 0))[1] if after else 0)
        assert start >= 0, (k, name, sub, txt)
        out[name] = (toks[idx[start]][1], start)
    return {n: v[0] for n, v in out.items()}, toks[0][1], toks[-1][2]

