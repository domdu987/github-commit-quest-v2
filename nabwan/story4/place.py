# "47 ครั้งที่ลบข้อความ": lay the Charon phrases (5 % faster takes) on a fresh timeline, write story4/vo.js + segments.
import json, subprocess
def split(f, n):
    return json.loads(subprocess.run(['venv/bin/python', '-I', 'scripts/split_phrases.py', f, str(n)], capture_output=True, text=True, check=True).stdout)['phrases']
src = {k: split(f'story4/vo/{k}44f.wav', n) for k, n in (('A', 9), ('B', 6), ('C', 9), ('D', 7))}
names = {'A': ['สามทุ่มตรง', 'เขาเปิดแชทของเธอ', 'พิมพ์ว่า', 'กินข้าวยัง', 'แล้วก็ลบ', 'พิมพ์ใหม่', 'แล้วก็ลบอีก', 'แค่คืนเดียว', 'ลบไปสี่สิบเจ็ดครั้ง'],
         'B': ['กลัวเธอรำคาญ', 'กลัวเธอไม่ตอบ', 'กลัวว่าที่แอบชอบ', 'จะเป็นแค่ฝ่ายเดียว', 'เลยได้แต่เปิดรูปโปรไฟล์', 'วนดูทั้งคืน'],
         'C': ['จนนิ้วเผลอกดส่ง', 'สติกเกอร์หมีกอด', 'ใจหล่นวูบ', 'แต่ไม่ถึงวินาที', 'เธอตอบกลับมาว่า', 'รอเธอทักอยู่ตั้งนาน', 'เพราะอีกฝั่ง', 'ก็พิมพ์แล้วลบ', 'ห้าสิบสองครั้งเหมือนกัน'],
         'D': ['บางที', 'คนที่เรากลัวว่าจะรำคาญ', 'อาจกำลังรอ', 'ข้อความจากเรา', 'กล้าทักสักครั้ง', 'ก่อนจะมีใคร', 'ทักเธอก่อนเรา']}
gaps = {'A': [0.4, 0.5, 0.2, 0.45, 0.35, 0.3, 0.55, 0.3, 0.7], 'B': [0.35, 0.5, 0.3, 0.6, 0.4, 0.7],
        'C': [0.3, 0.45, 0.55, 0.3, 0.3, 0.6, 0.25, 0.3, 0.0], 'D': [0.3, 0.45, 0.25, 0.55, 0.45, 0.25, 0.0]}
DROP = set()
TITLE = 2.6; END = 3.2
t = 0.4
ph = []
for k in 'ABCD':
    if k == 'D': t += TITLE + 0.2
    for i, (a, b) in enumerate(src[k]):
        if f'{k}{i}' in DROP: continue
        ph.append({'id': f'{k}{i}', 'take': k, 'name': names[k][i], 'src': [a, b], 'on': round(t, 3), 'off': round(t + b - a, 3)})
        t += (b - a) + gaps[k][i]
g = {p['id']: p for p in ph}
title_at = g['C8']['off'] + 0.25
end_at = ph[-1]['off'] + 0.45
DUR = round(end_at + END, 2)
for p in ph: print(f"{p['id']:3s} {p['name']:24s} {p['on']:6.2f}-{p['off']:6.2f}")
print('title', round(title_at, 2), 'end card', round(end_at, 2), 'DUR', DUR)
on = lambda k: g[k]['on']; d = lambda k: g[k]['off'] - g[k]['on']
P = {p['id']: p['on'] for p in ph}
P.update({'title': round(title_at, 3), 'end': round(end_at, 3), 'DUR': DUR})
def part(t_, s, k, at=None, dd=None): return {'t': t_, 's': s, 'at': round(at if at is not None else on(k), 3), 'd': round(dd if dd is not None else d(k), 3)}
cues = [
 [part('3 ทุ่มตรง', 'r', 'A0')],
 [part('เขาเปิดแชทของเธอ', 'w', 'A1')],
 [part('พิมพ์ว่า', 'w', 'A2'), part(' "กินข้าวยัง"', 'y', 'A3')],
 [part('แล้วก็ลบ', 'w', 'A4'), part(' พิมพ์ใหม่', 'w', 'A5'), part(' แล้วก็ลบอีก', 'w', 'A6')],
 [part('แค่คืนเดียว', 'w', 'A7'), part(' ลบไป', 'w', 'A8', dd=0.6), part('47 ครั้ง', 'r', 'A8', at=on('A8') + 0.6, dd=d('A8') - 0.6)],
 [part('กลัวเธอรำคาญ', 'w', 'B0'), part(' กลัวเธอไม่ตอบ', 'w', 'B1')],
 [part('กลัวว่าที่แอบชอบ', 'w', 'B2'), part(' จะเป็นแค่', 'w', 'B3', dd=0.7), part('ฝ่ายเดียว', 'r', 'B3', at=on('B3') + 0.7, dd=d('B3') - 0.7)],
 [part('เลยได้แต่เปิดรูปโปรไฟล์', 'w', 'B4'), part(' วนดูทั้งคืน', 'w', 'B5')],
 [part('จนนิ้วเผลอกดส่ง', 'y', 'C0')],
 [part('สติกเกอร์หมีกอด', 'w', 'C1')],
 [part('ใจหล่นวูบ', 'r', 'C2')],
 [part('แต่ไม่ถึงวินาที', 'w', 'C3')],
 [part('เธอตอบกลับมาว่า', 'w', 'C4'), part(' "รอเธอทักอยู่ตั้งนาน"', 'y', 'C5')],
 [part('เพราะอีกฝั่ง', 'w', 'C6'), part(' ก็พิมพ์แล้วลบ', 'w', 'C7')],
 [part('52 ครั้ง', 'r', 'C8', dd=0.9), part(' เหมือนกัน', 'w', 'C8', at=on('C8') + 0.9, dd=d('C8') - 0.9)],
 [part('บางที', 'w', 'D0'), part(' คนที่เรากลัวว่าจะรำคาญ', 'w', 'D1')],
 [part('อาจกำลังรอ', 'w', 'D2'), part(' ข้อความจากเรา', 'y', 'D3')],
 [part('กล้าทักสักครั้ง', 'y', 'D4')],
 [part('ก่อนจะมีใคร', 'w', 'D5'), part(' ทักเธอก่อนเรา', 'r', 'D6')],
]
CUES = []
for j, parts in enumerate(cues):
    a = parts[0]['at']
    last_end = max(p['at'] + p['d'] for p in parts)
    nxt = cues[j + 1][0]['at'] if j + 1 < len(cues) else 99
    b = min(nxt - 0.04, last_end + 0.6)
    CUES.append({'a': round(a, 3), 'b': round(b, 3), 'parts': parts})
CUES[-1]['b'] = round(end_at - 0.05, 3)
open('story4/vo.js', 'w').write('// generated by story4/place.py\nconst VO = ' + json.dumps({'P': P, 'CUES': CUES}, ensure_ascii=False) + ';\n')
json.dump([{'file': f'story4/vo/{p["take"]}44f.wav', 'src': p['src'], 'on': p['on'], 'name': p['name']} for p in ph], open('story4/segments.json', 'w'), ensure_ascii=False, indent=1)
