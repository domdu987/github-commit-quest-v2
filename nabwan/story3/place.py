# "1,095 ข้อความของแม่": lay the Charon phrases (5 % faster takes) on a fresh timeline, write story3/vo.js + segments.
import json, subprocess
def split(f, n):
    return json.loads(subprocess.run(['venv/bin/python', '-I', 'scripts/split_phrases.py', f, str(n)], capture_output=True, text=True, check=True).stdout)['phrases']
src = {k: split(f'story3/vo/{k}44f.wav', n) for k, n in (('A', 9), ('B', 8), ('C', 10), ('D', 7))}
names = {'A': ['ทุกเช้า', 'หกโมงตรง', 'แม่จะส่งรูปดอกไม้', 'มาทักทาย', 'สวัสดีวันจันทร์', 'ขอให้ลูกสุขสบาย', 'สามปีไม่เคยหาย', 'รวมแล้ว', 'หนึ่งพันเก้าสิบห้าข้อความ'],
         'B': ['แต่ลูกแค่เปิดอ่าน', 'แล้วก็ปัดผ่านไป', 'บางวันกดปิดแจ้งเตือน', 'เพราะรำคาญใจ', 'โดยไม่รู้เลยว่า', 'แม่ใช้นิ้วเดียว', 'ค่อยๆ จิ้ม', 'กว่าจะส่งได้'],
         'C': ['จนเช้าวันหนึ่ง', 'หกโมง', 'เจ็ดโมง', 'แปดโมง', 'ไม่มีดอกไม้', 'จอเงียบจนใจหาย', 'ลูกรีบโทรหา', 'เสียงแม่แผ่วเบา', 'แม่แค่ไม่สบาย', 'ไม่ต้องห่วงนะลูก'],
         'D': ['ข้อความที่เราว่าน่ารำคาญ', 'คือหลักฐาน', 'ว่ายังมีคนคิดถึง', 'วันนี้', 'ตอบแม่สักคำ', 'ก่อนวันที่', 'ไม่มีใครส่งมา']}
gaps = {'A': [0.3, 0.45, 0.25, 0.45, 0.3, 0.4, 0.45, 0.2, 0.5], 'B': [0.25, 0.45, 0.25, 0.5, 0.35, 0.3, 0.3, 0.5],
        'C': [0.45, 0.35, 0.35, 0.4, 0.3, 0.45, 0.4, 0.0, 0.35, 0.0], 'D': [0.3, 0.4, 0.5, 0.3, 0.4, 0.35, 0.0]}
DROP = {'C7'}
TITLE = 2.4; END = 3.0
t = 0.4
ph = []
for k in 'ABCD':
    if k == 'D': t += TITLE + 0.2
    for i, (a, b) in enumerate(src[k]):
        if f'{k}{i}' in DROP: continue
        ph.append({'id': f'{k}{i}', 'take': k, 'name': names[k][i], 'src': [a, b], 'on': round(t, 3), 'off': round(t + b - a, 3)})
        t += (b - a) + gaps[k][i]
g = {p['id']: p for p in ph}
title_at = g['C9']['off'] + 0.2
end_at = ph[-1]['off'] + 0.45
DUR = round(end_at + END, 2)
for p in ph: print(f"{p['id']:3s} {p['name']:24s} {p['on']:6.2f}-{p['off']:6.2f}")
print('title', round(title_at, 2), 'end card', round(end_at, 2), 'DUR', DUR)
on = lambda k: g[k]['on']; d = lambda k: g[k]['off'] - g[k]['on']
P = {p['id']: p['on'] for p in ph}
P.update({'title': round(title_at, 3), 'end': round(end_at, 3), 'DUR': DUR})
def part(t_, s, k, at=None, dd=None): return {'t': t_, 's': s, 'at': round(at if at is not None else on(k), 3), 'd': round(dd if dd is not None else d(k), 3)}
cues = [
 [part('ทุกเช้า', 'w', 'A0'), part(' 6 โมงตรง', 'r', 'A1')],
 [part('แม่จะส่งรูปดอกไม้', 'w', 'A2'), part(' มาทักทาย', 'w', 'A3')],
 [part('สวัสดีวันจันทร์', 'y', 'A4')],
 [part('ขอให้ลูกสุขสบาย', 'w', 'A5')],
 [part('3 ปี', 'r', 'A6', dd=0.7), part(' ไม่เคยหาย', 'w', 'A6', at=on('A6') + 0.75, dd=d('A6') - 0.75)],
 [part('รวมแล้ว', 'w', 'A7'), part(' 1,095 ข้อความ', 'r', 'A8')],
 [part('แต่ลูกแค่เปิดอ่าน', 'w', 'B0')],
 [part('แล้วก็ปัดผ่านไป', 'w', 'B1')],
 [part('บางวันกด', 'w', 'B2', dd=0.7), part('ปิดแจ้งเตือน', 'r', 'B2', at=on('B2') + 0.7, dd=d('B2') - 0.7)],
 [part('เพราะรำคาญใจ', 'w', 'B3')],
 [part('โดยไม่รู้เลยว่า', 'y', 'B4')],
 [part('แม่ใช้', 'w', 'B5', dd=0.45), part('นิ้วเดียว', 'r', 'B5', at=on('B5') + 0.45, dd=d('B5') - 0.45)],
 [part('ค่อยๆ จิ้ม', 'w', 'B6'), part(' กว่าจะส่งได้', 'w', 'B7')],
 [part('จนเช้าวันหนึ่ง', 'y', 'C0')],
 [part('6 โมง', 'w', 'C1'), part(' 7 โมง', 'w', 'C2'), part(' 8 โมง', 'r', 'C3')],
 [part('ไม่มีดอกไม้', 'w', 'C4')],
 [part('จอเงียบ', 'w', 'C5', dd=0.7), part('จนใจหาย', 'r', 'C5', at=on('C5') + 0.7, dd=d('C5') - 0.7)],
 [part('ลูกรีบโทรหา', 'w', 'C6')],
 [part('แม่แค่ไม่สบาย', 'w', 'C8'), part(' ไม่ต้องห่วงนะลูก', 'y', 'C9')],
 [part('ข้อความที่เราว่าน่ารำคาญ', 'w', 'D0')],
 [part('คือหลักฐาน', 'r', 'D1'), part(' ว่ายังมีคนคิดถึง', 'w', 'D2')],
 [part('วันนี้', 'y', 'D3'), part(' ตอบแม่สักคำ', 'y', 'D4')],
 [part('ก่อนวันที่', 'w', 'D5'), part(' ไม่มีใครส่งมา', 'r', 'D6')],
]
CUES = []
for j, parts in enumerate(cues):
    a = parts[0]['at']
    last_end = max(p['at'] + p['d'] for p in parts)
    nxt = cues[j + 1][0]['at'] if j + 1 < len(cues) else 99
    b = min(nxt - 0.04, last_end + 0.6)
    CUES.append({'a': round(a, 3), 'b': round(b, 3), 'parts': parts})
CUES[-1]['b'] = round(end_at - 0.05, 3)
open('story3/vo.js', 'w').write('// generated by story3/place.py\nconst VO = ' + json.dumps({'P': P, 'CUES': CUES}, ensure_ascii=False) + ';\n')
json.dump([{'file': f'story3/vo/{p["take"]}44f.wav', 'src': p['src'], 'on': p['on'], 'name': p['name']} for p in ph], open('story3/segments.json', 'w'), ensure_ascii=False, indent=1)
