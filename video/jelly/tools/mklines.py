def mk(rows, seg=""):
    out = []
    for r in rows:
        lid, who, text, cap, emo = r[:5]
        voice, tempo, persona = CAST[who]
        ln = {"id": lid, "text": text, "voice": voice,
              "style": NARR if who == "n" else f"{persona} {emo} {TAIL}", "tempo": tempo, "cap": cap}
        if len(r) > 5:
            ln["only"] = r[5]
        if (seg, lid) in FULL_ONLY:
            ln["only"] = "full"
        if TAKES.get((seg, lid)):
            ln["take"] = TAKES[(seg, lid)]
        # the caption must say exactly what is spoken
        assert re.sub(r"[\[\]{}]", "", cap).replace(" / ", " ") == text, (seg, lid, cap)
        out.append(ln)
    ids = [l["id"] for l in out]
    assert len(ids) == len(set(ids)), "duplicate id"
    return out


